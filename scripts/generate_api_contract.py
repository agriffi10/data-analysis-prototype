"""Emits the browser's view of the wire contract from the one Python declaration.

The API is Python and the SPA is TypeScript. Rather than keep two copies in step by hand — which
rots, and rots silently, because nothing fails until a field a caller stopped sending is one a
handler still reads — the TypeScript is generated from ``apicommon.contract`` and CI fails on a
regeneration diff. That gate catches drift in BOTH directions: a Python type edited without
regenerating, and the generated TypeScript edited by hand.

The second gate is the compiler. A field removed or renamed in Python regenerates into a changed
TypeScript type and fails at every call site, which is a thing no test has to be written for.

**This emitter never falls back.** ``contract.walk`` raises on a shape outside the closed
vocabulary and this module lets that reach the caller, because emitting ``unknown`` or ``any``
for an unfamiliar shape produces a type that agrees with every possible value — a contract that
has stopped checking anything while every gate stays green.

Attributes:
  HEADER: The banner every generated file carries. Without it a formatter reformats a file no
    human wrote, and the regeneration gate then rejects the formatting.
  OUTPUT: Where the generated module is written, relative to the repository root.
  SCALARS: Each scalar node kind to the TypeScript type it emits as.
"""

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "lambdas" / "api"))

from apicommon import contract
from apicommon.contract import TypeNode

HEADER = "// GENERATED by scripts/generate_api_contract.py — do not edit."
OUTPUT = pathlib.Path("apps/portal/src/types/apiContract.generated.ts")

SCALARS = {"str": "string", "int": "number", "float": "number", "bool": "boolean", "none": "null"}


def render(node: TypeNode) -> str:
    """Renders one normalised node as a TypeScript type expression.

    An object renders as its NAME rather than inline, so a shape referenced twice is one
    declaration rather than two structural copies that a later edit can separate.

    Args:
      node: The normalised node.

    Returns:
      The TypeScript type expression.

    Raises:
      ValueError: If the node's kind is not one this emitter renders, which can only mean the
        vocabulary grew in the contract without growing here.
    """
    if node.kind in SCALARS:
        return SCALARS[node.kind]
    if node.kind == "literal":
        return " | ".join(f"'{value}'" for value in node.literals)
    if node.kind == "optional":
        return f"{render(node.of[0])} | null"
    if node.kind == "list":
        inner = render(node.of[0])
        return f"({inner})[]" if _renders_a_union(node.of[0]) else f"{inner}[]"
    if node.kind == "object":
        return node.name
    raise ValueError(f"no TypeScript rendering for node kind {node.kind!r}")


def _renders_a_union(node: TypeNode) -> bool:
    """Whether a node renders as a union at the TOP level, so a list of it needs parentheses.

    Decided by KIND rather than by looking for a space in the rendered string. The string test
    reads a nested list's own parentheses as a union — ``list[list[str | None]]`` came out as
    ``((string | null)[])[]``, which is the same type and not the same bytes, and this file's
    whole gate is a byte comparison.

    Args:
      node: The contained node.

    Returns:
      True if it renders as ``A | B``.

    Raises:
      None.
    """
    return node.kind == "optional" or (node.kind == "literal" and len(node.literals) > 1)


def render_declaration(node: TypeNode) -> str:
    """Renders one object node as an exported TypeScript type declaration.

    A type with NO fields renders as ``Record<string, never>`` rather than ``{}``, because ``{}``
    in TypeScript agrees with every non-null value — so a route answering an empty body would be
    typed by something that checks nothing, which is the fallback this emitter exists to refuse.
    The empty case arrives with the first route whose 200 carries no payload.

    Args:
      node: The object node.

    Returns:
      The ``export type Name = {...};`` line.

    Raises:
      ValueError: If the node is not an object.
    """
    if node.kind != "object":
        raise ValueError(f"only an object node is a declaration, not {node.kind!r}")
    if not node.fields:
        return f"export type {node.name} = Record<string, never>;"
    members = "; ".join(
        f"{name}{'' if required else '?'}: {render(child)}" for name, child, required in node.fields
    )
    return f"export type {node.name} = {{{members}}};"


def generate() -> str:
    """Builds the whole generated module.

    Every ordering here is a function of the declaration alone — the routes in declaration order,
    the types in first-seen order, the codes in the order the literal union declares them — so
    running this twice produces the same bytes and the regeneration gate means something.

    Args:
      None.

    Returns:
      The file's contents.

    Raises:
      UnsupportedTypeError: If any declared type is outside the contract's vocabulary.
    """
    contract.check_routes()
    lines = [HEADER, ""]

    for declared in contract.declared_types():
        lines.append(render_declaration(contract.walk(declared)))
    lines.append("")

    # From the ENUM's own declaration, never from a field position. Read positionally
    # (`ApiErrorDetail.fields[0]`) this emits an empty list the moment the error type's fields are
    # reordered — which Premise 4 invites by reserving a typed `params` object — and both wording
    # guards then pass over an empty set while looking green.
    codes = contract.walk(contract.ErrorCode).literals
    if not codes:
        raise ValueError("the error enum emitted empty; both wording guards would pass vacuously")
    lines.append(
        "export const API_ERROR_CODES = ["
        + ", ".join(f"'{code}'" for code in codes)
        + "] as const;"
    )
    lines.append("export type ApiErrorCode = (typeof API_ERROR_CODES)[number];")
    lines.append("")

    lines.append("export const API_ROUTES = {")
    for route in contract.ROUTES:
        params = ", ".join(f"'{name}'" for name in contract.path_parameters(route.path))
        lines.append(
            f"  '{route.id}': {{method: '{route.method}', path: '{route.path}', "
            f"idempotent: {'true' if route.idempotent else 'false'}, params: [{params}]}},"
        )
    lines.append("} as const;")
    lines.append("")
    lines.append("export type ApiRouteId = keyof typeof API_ROUTES;")
    lines.append("")
    lines.append(
        "export type PathParamsOf<R extends ApiRouteId> = "
        "{[K in (typeof API_ROUTES)[R]['params'][number]]: string};"
    )
    lines.append("")

    lines.append("type RouteBodies = {")
    for route in contract.ROUTES:
        request = "null" if route.request is None else route.request.__name__
        query = "null" if route.query is None else route.query.__name__
        lines.append(
            f"  '{route.id}': {{request: {request}; query: {query}; "
            f"response: {route.response.__name__}}};"
        )
    lines.append("};")
    lines.append("")
    lines.append("export type RequestOf<R extends ApiRouteId> = RouteBodies[R]['request'];")
    lines.append("export type QueryOf<R extends ApiRouteId> = RouteBodies[R]['query'];")
    lines.append("export type ResponseOf<R extends ApiRouteId> = RouteBodies[R]['response'];")

    return "\n".join(lines) + "\n"


def main() -> int:
    """Writes the generated module.

    Args:
      None.

    Returns:
      The process exit code.

    Raises:
      UnsupportedTypeError: If a declared type is outside the vocabulary. Deliberately not caught:
        a generator that reports success having emitted a fallback is the failure this refuses.
    """
    target = ROOT / OUTPUT
    target.write_text(generate(), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
